    private static bool _english;

    /// <summary>Английский язык выбран.</summary>
    public static bool IsEnglish => _english;

    /// <summary>
    /// Выбрать язык.
    /// </summary>
    /// <param name="language">
    /// «ru», «en» или пустое значение — тогда язык берётся из настроек системы.
    /// </param>
    public static void Use(string? language)
    {
        _english = language?.ToLowerInvariant() switch
        {
            "en" => true,
            "ru" => false,

            // Русский для русской системы, английский для любой другой:
            // угадывать по одному языку из сотни бессмысленно, а два
            // покрывают ровно то, что переведено.
            _ => !CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.Equals("ru", StringComparison.OrdinalIgnoreCase),
        };

        // Вместе с языком меняется запись чисел и дат. Иначе английский текст
        // соседствовал бы с «1,5 ГБ» и «05.09.2026» — мелочь, по которой сразу
        // видно, что перевод сделан наполовину.
        //
        // Меняется только вывод: журнал и настройки пишутся в неизменном виде,
        // потому что идут через инвариантную культуру.
        if (language is not null)
        {
            var culture = new CultureInfo(_english ? "en-US" : "ru-RU");

            CultureInfo.CurrentCulture = culture;
            CultureInfo.CurrentUICulture = culture;
        }
    }

    /// <summary>Текст по ключу.</summary>
    public static string Get(string key)
    {
        if (_english && English.TryGetValue(key, out var english))
        {
            return english;
        }

        // Ключ вместо фразы — это внутренности программы на виду у человека.
        // Русский текст здесь честнее.
        return Russian.TryGetValue(key, out var russian) ? russian : key;
    }

    /// <summary>Ключи, для которых нет английского перевода. Нужно проверке полноты.</summary>
    internal static IEnumerable<string> MissingEnglishKeys() => Russian.Keys.Where(k => !English.ContainsKey(k));
